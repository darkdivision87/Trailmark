  startTask:id=>ipcRenderer.invoke('start-task',id),
  endApp:(id,processes)=>ipcRenderer.invoke('end-app',id,processes),
  getNews:()=>ipcRenderer.invoke('get-news'),
  refreshNews:()=>ipcRenderer.invoke('refresh-news'),
  openHeadline:url=>ipcRenderer.invoke('open-headline',url),
