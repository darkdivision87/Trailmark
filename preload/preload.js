  saveProject: project => ipcRenderer.invoke('save-project',project),
  deleteProject: id => ipcRenderer.invoke('delete-project',id),
  assignProject: (id,projectId) => ipcRenderer.invoke('assign-project',id,projectId),
  saveTask: task=>ipcRenderer.invoke('save-task',task),
  timeTask: (id,running)=>ipcRenderer.invoke('time-task',id,running),
  moveTask: (id,target,position)=>ipcRenderer.invoke('move-task',id,target,position),
  openTaskLink: id=>ipcRenderer.invoke('open-task-link',id),
