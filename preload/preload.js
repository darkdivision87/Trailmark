  copyMediaPair: ()=>ipcRenderer.invoke('copy-media-pair'),
  pairMedia: ()=>ipcRenderer.invoke('pair-media'),
  openMediaHelper: ()=>ipcRenderer.invoke('open-media-helper'),
  mediaTabAction: (browser,id,action,clientId)=>ipcRenderer.invoke('media-tab-action',browser,id,action,clientId),
  openVolumeMixer: ()=>ipcRenderer.invoke('open-volume-mixer'),
  getClipboard: ()=>ipcRenderer.invoke('get-clipboard'),
  addLauncher:()=>ipcRenderer.invoke('launcher-add'),
  openLauncher:id=>ipcRenderer.invoke('launcher-open',id),
  removeLauncher:id=>ipcRenderer.invoke('launcher-remove',id),
  getClipboardImage:id=>ipcRenderer.invoke('clipboard-image',id),
  saveCurrentClipboard: ()=>ipcRenderer.invoke('clipboard-save-current'),
  copyClipboard: id=>ipcRenderer.invoke('clipboard-copy',id),
  pinClipboard: (id,pinned)=>ipcRenderer.invoke('clipboard-pin',id,pinned),
